const noop = () => { };

function errorMessage(error: unknown): string {
    return error instanceof Error ? error.message : String(error);
}

/** Cancel whichever task is currently running (yt-dlp or ffmpeg). */
export function cancelCurrentTask() {
    return taskManager.cancelCurrentTask();
}

/** Run yt-dlp with the given argument array and stream progress lines. */
export async function runYtDlp(args: string[], onProgress: Progress = noop): Promise<DownloadResult> {
    const finalArgs = args.includes('--remote-components')
        ? args
        : ['--remote-components', 'ejs:github', ...args];
    logger.info('Executing:', finalArgs);

    let task;
    try {
        task = taskManager.startTask('run-command');
    } catch (err) {
        return {
            success: false,
            cancelled: false,
            code: -1,
            output: '',
            error: errorMessage(err)
        };
    }

    return new Promise<DownloadResult>((resolve) => {
        let child;
        try {
            child = taskManager.spawnProcess(task, 'yt-dlp', finalArgs);
        } catch (err) {
            taskManager.endTask(task);
            resolve({
                success: false,
                cancelled: false,
                code: -1,
                output: '',
                error: errorMessage(err)
            });
            return;
        }

        const outputLines: string[] = [];
        let lastProgressLine: string | null = null;

        const handleCleanLine = (line: string) => {
            const trimmed = line.trim();
            const isProgress = isProgressLine(trimmed);

            if (isProgress || trimmed.startsWith('[download]')) {
                onProgress(trimmed);
            }
            if (isProgress) {
                lastProgressLine = line;
            } else {
                if (lastProgressLine) {
                    outputLines.push(lastProgressLine);
                    lastProgressLine = null;
                }
                outputLines.push(line);
            }
        };

        const flushFilters = attachLineStreamFilters(child, handleCleanLine);

        child.on('close', (code) => {
            flushFilters();

            if (lastProgressLine) {
                outputLines.push(lastProgressLine);
            }

            const wasCancelled = task.isCancelled;
            taskManager.endTask(task);

            const output = outputLines.join('\n').trim();
            if (wasCancelled) {
                resolve({
                    success: false,
                    cancelled: true,
                    code: code ?? -1,
                    output: 'Action cancelled by user.',
                    error: 'Action cancelled by user.'
                });
            } else if (code !== 0) {
                resolve({
                    success: false,
                    cancelled: false,
                    code,
                    output,
                    error: `Process exited with code ${code}`
                });
            } else {
                resolve({
                    success: true,
                    cancelled: false,
                    code: 0,
                    output,
                    error: ''
                });
            }
        });
    });
}

/** Run a short, non-task yt-dlp query for metadata or format information. */
async function queryYtDlp(args: string[]): Promise<QueryResult> {
    const executable = await findExecutable('yt-dlp');
    if (!executable) {
        return { ok: false, output: '', error: 'yt-dlp is not installed.' };
    }
    return new Promise<QueryResult>((resolve) => {
        try {
            const child = spawnYtDlp(executable, args);
            // Decode as a stream so multi-byte characters split across chunks stay intact.
            child.stdout.setEncoding('utf8');
            child.stderr.setEncoding('utf8');
            let stdout = '';
            let stderr = '';
            child.stdout.on('data', (d) => stdout += d);
            child.stderr.on('data', (d) => stderr += d);
            child.on('error', (err) => {
                logger.error('yt-dlp query process error:', err);
                resolve({ ok: false, output: '', error: errorMessage(err) });
            });
            child.on('close', (code) => {
                resolve({ ok: code === 0, output: stdout.trim(), error: stderr.trim() });
            });
        } catch (err) {
            resolve({ ok: false, output: '', error: errorMessage(err) });
        }
    });
}

