/** Fetch online video metadata without downloading. */
export async function getOnlineVideoInfo(url: string, options: { browser?: string; proxy?: string } = {}): Promise<OnlineVideoInfo> {
    const { browser, proxy } = options;
    const args = ['--no-playlist', '--skip-download', '--remote-components', 'ejs:github'];
    if (browser) {
        args.push('--cookies-from-browser', browser);
    }
    if (proxy) {
        args.push('--proxy', proxy);
    }
    args.push('--print', '%(title)s\t%(uploader)s\t%(duration_string)s\t%(is_live)s', url);

    const res = await queryYtDlp(args);
    if (!res.ok) {
        return { ok: false, error: res.error };
    }
    const [title = '', uploader = '', duration = '', isLive = ''] = (res.output || '').split('\n')[0].split('\t');
    return { ok: true, title, uploader, duration, is_live: isLive === 'True' };
}

function findOriginalCaption(captions: CaptionFormats, language?: string) {
    const codes = Object.keys(captions).filter((code) => Array.isArray(captions[code]) && captions[code].length > 0);
    const originals = codes.filter((code) => code.endsWith('-orig'));
    const lang = language?.toLowerCase();
    if (lang) {
        const exact = originals.find((code) => code.toLowerCase() === `${lang}-orig`);
        if (exact) return exact;

        // YouTube can report en-US for the audio while labeling its captions en-orig.
        const primaryLanguage = lang.split('-')[0];
        const related = originals.filter((code) => code.toLowerCase().split('-')[0] === primaryLanguage);
        if (related.length === 1) return related[0];
    }
    if (originals.length === 1) return originals[0];
    return codes.find((code) => code.toLowerCase() === lang);
}

/** Extract manual / original-language auto subtitles from a yt-dlp info JSON object. */
function extractSubtitleChoices(info: VideoCaptions, forTranscript: boolean): SubtitleChoices {
    const manualSubtitles: SubtitleTrack[] = [];
    const autoGenerated: SubtitleTrack[] = [];

    // Get manually uploaded subtitles
    if (info.subtitles) {
        for (const [code, formats] of Object.entries(info.subtitles)) {
            if (formats && formats.length > 0) {
                const name = formats[0].name || code.toUpperCase();
                manualSubtitles.push({ code, name, type: 'manual' });
            }
        }
    }

    const captions = info.automatic_captions || {};
    const language = typeof info.language === 'string' ? info.language.trim() || undefined : undefined;
    const key = findOriginalCaption(captions, language);
    const originalLanguage = key?.endsWith('-orig') ? key.slice(0, -5) : language;
    if (key) {
        const fallbackName = (originalLanguage || key).toUpperCase();
        const rawName = captions[key][0]?.name;
        const name = typeof rawName === 'string' ? rawName.replace(/\(Original\)/gi, '').trim() || fallbackName : fallbackName;
        autoGenerated.push({ code: key, name, type: 'auto-original' });
    }

    if (forTranscript) {
        return { subtitles: [...manualSubtitles, ...autoGenerated], isAutoGenerated: manualSubtitles.length === 0 && autoGenerated.length > 0, originalLanguage };
    }

    // Priority: manual subtitles first, then auto-generated
    if (manualSubtitles.length > 0) {
        logger.info('Found manual subtitles:', manualSubtitles);
        return { subtitles: manualSubtitles, isAutoGenerated: false };
    }
    if (autoGenerated.length > 0) {
        logger.info('No manual subtitles, showing auto-generated:', autoGenerated);
        return { subtitles: autoGenerated, isAutoGenerated: true };
    }
    logger.info('No subtitles available');
    return { subtitles: [], isAutoGenerated: false };
}

/** List the subtitle languages available for a video. */
export function listSubtitles(url: string, browser?: string, proxy?: string, { forTranscript = false, signal }: {
    forTranscript?: boolean;
    signal?: AbortSignal;
} = {}): Promise<SubtitleListing> {
    logger.info('Listing subtitles for:', url);

    const failure = (message: string): SubtitleListing => ({ success: false, error: true, message, subtitles: [], isAutoGenerated: false });

    return findExecutable('yt-dlp').then((executable) => new Promise<SubtitleListing>((resolve) => {
        if (!executable) {
            resolve(failure('yt-dlp is not installed.'));
            return;
        }
        try {
            // --no-playlist: for a link like watch?v=X&list=Y, -j would otherwise print one JSON document
            // per playlist entry, which cannot be parsed as a single video.
            const args = ['-j', '--no-playlist', '--skip-download', '--remote-components', 'ejs:github'];
            if (forTranscript) args.push('--ignore-config', '--playlist-items', '1');
            if (proxy) args.push('--proxy', proxy);
            if (browser) args.push('--cookies-from-browser', browser);
            args.push(url);

            const child = spawnYtDlp(executable, args, { signal });
            child.stdout.setEncoding('utf8');
            child.stderr.setEncoding('utf8');
            let stdout = '';
            let stderr = '';

            child.stdout.on('data', (data) => stdout += data);
            child.stderr.on('data', (data) => stderr += data);
            child.on('error', (err) => {
                if (err.name !== 'AbortError') logger.error('list-subtitles process error:', err);
                resolve(failure(errorMessage(err)));
            });

            child.on('close', (code) => {
                if (signal?.aborted) {
                    resolve(failure('Action cancelled by user.'));
                    return;
                }
                if (code !== 0) {
                    logger.error('Error getting video info:', stderr);
                    resolve(failure(stderr || 'Unknown error'));
                    return;
                }

                try {
                    const info = JSON.parse(stdout);
                    const choices = extractSubtitleChoices(info, forTranscript);
                    resolve({ success: true, error: false, message: '', ...choices });
                } catch (parseError) {
                    logger.error('Error parsing video info:', parseError);
                    resolve(failure('Failed to parse video information'));
                }
            });
        } catch (err) {
            resolve(failure(errorMessage(err)));
        }
    }));
}

/** Re-encode a downloaded video in `downloadFolder` to MP4 (H.264/AAC). */
export async function reEncodeToMp4(downloadFolder: string, videoId: string, onProgress: Progress = noop): Promise<ConversionResult> {
    logger.info('Re-encoding video in folder:', downloadFolder, 'for video ID:', videoId);

    let task;
    try {
        task = taskManager.startTask('re-encode');
    } catch (err) {
        return {
            success: false,
            cancelled: false,
            message: `Error: ${errorMessage(err)}`,
            error: errorMessage(err),
            tmpFiles: []
        };
    }

    try {
        const media = await findVideoToReEncode(downloadFolder, videoId);
        if (!media) {
            return {
                success: false,
                cancelled: false,
                message: 'No matching video file found to re-encode.',
                error: 'No matching video file found to re-encode.',
                tmpFiles: []
            };
        }

        const { file, filePath, filename, thumbnailPath } = media;
        const outputPath = join(downloadFolder, `${filename}_reencoded.mp4`);

        logger.info(`Re-encoding file: ${file}`);
        onProgress(`Re-encoding ${file}...`);

        const result = await runFfmpegWithCodecFallback({
            task,
            onProgress,
            buildArgs: (audioCodec) => buildFfmpegReEncodeArgs({ filePath, outputPath, thumbnailPath, audioCodec }),
            outputPath,
            logPrefix: `Re-encoding ${file}`
        });

        if (result.isCancelled) {
            logger.info('Re-encoding was cancelled. Cleaning up temporary output only...');
            try { await fs.unlink(outputPath); } catch { /* ignore */ }
            return {
                success: false,
                cancelled: true,
                message: 'Re-encoding cancelled by user. Files cleaned up.',
                error: 'Action cancelled by user.',
                tmpFiles: []
            };
        }

        if (result.success) {
            const finalPath = join(downloadFolder, `${filename}.mp4`);
            await fs.rename(outputPath, finalPath);
            logger.info(`Successfully re-encoded: ${file} to ${finalPath}`);

            const tmpFiles = [];
            if (filePath !== finalPath) tmpFiles.push(filePath);
            if (thumbnailPath && thumbnailPath !== finalPath) tmpFiles.push(thumbnailPath);

            return {
                success: true,
                cancelled: false,
                message: `Re-encoding completed successfully. Saved as: ${filename}.mp4`,
                tmpFiles: offerTempFiles(tmpFiles)
            };
        } else {
            try { await fs.unlink(outputPath); } catch { /* ignore */ }
            return {
                success: false,
                cancelled: false,
                message: `Failed to re-encode ${file} with exit code ${result.lastCode}`,
                error: `Process exited with code ${result.lastCode}`,
                tmpFiles: []
            };
        }
    } catch (error) {
        return {
            success: false,
            cancelled: false,
            message: `Error during re-encoding: ${errorMessage(error)}`,
            error: errorMessage(error),
            tmpFiles: []
        };
    } finally {
        taskManager.endTask(task);
    }
}

/** Inspect a local media file with ffprobe. */
export async function getLocalMediaInfo(downloadFolder: string, fileHint: string) {
    const media = await findMediaFile(downloadFolder, fileHint);
    if (!media) {
        return {
            ok: false as const,
            error: `No matching media file found for "${fileHint}" in the download folder.`
        };
    }
    const res = await probeMedia(media.filePath);
    if (!res.ok) {
        return { ok: false as const, error: res.error };
    }
    return summarizeMediaInfo(res.data, media.file);
}


/** Extract audio from a media file in the download folder. */
export async function extractAudioFromFile(
    downloadFolder: string, fileHint: string, options: { format?: string } = {}, onProgress: Progress = noop
): Promise<AudioExtractionResult> {
    const format = options.format || 'best';
    logger.info('Extracting audio from file:', { downloadFolder, fileHint, format });

    let task;
    try {
        task = taskManager.startTask('extract-audio');
    } catch (err) {
        return {
            success: false,
            cancelled: false,
            message: `Error: ${errorMessage(err)}`,
            error: errorMessage(err)
        };
    }

    try {
        const media = await findMediaFile(downloadFolder, fileHint);
        if (!media) {
            return {
                success: false,
                cancelled: false,
                message: `No matching media file found for "${fileHint}" in the download folder.`,
                error: `No matching media file found for "${fileHint}" in the download folder.`
            };
        }

        // Probe media to discover audio streams and native codec
        const probeRes = await probeMedia(media.filePath);
        if (!probeRes.ok) {
            return {
                success: false,
                cancelled: false,
                message: `Failed to probe media file: ${probeRes.error}`,
                error: probeRes.error
            };
        }

        const streams = Array.isArray(probeRes.data?.streams) ? probeRes.data.streams : [];
        const audioStream = streams.find((s) => s.codec_type === 'audio');
        if (!audioStream) {
            return {
                success: false,
                cancelled: false,
                message: `No audio stream found in "${media.file}".`,
                error: `No audio stream found in "${media.file}".`
            };
        }

        const nativeCodec = (audioStream.codec_name || '').toLowerCase();
        const ext = determineAudioExtension(format, nativeCodec);
        const baseName = parse(media.file).name;

        // Choose non-conflicting final filename
        let finalFilename = `${baseName}.${ext}`;
        let finalPath = join(downloadFolder, finalFilename);
        try {
            await fs.stat(finalPath);
            finalFilename = `${baseName}_audio.${ext}`;
            finalPath = join(downloadFolder, finalFilename);
        } catch { /* safe to use original filename */ }

        const tempFilename = `${baseName}_extracting_${Date.now()}.${ext}`;
        const tempPath = join(downloadFolder, tempFilename);

        onProgress(`Extracting audio (${ext}) from ${media.file}...`);

        const args = buildFfmpegExtractAudioArgs({
            inputPath: media.filePath,
            outputPath: tempPath,
            format,
            nativeCodec
        });

        const result = await runFfmpegProcess({
            task,
            args,
            onProgress,
            logPrefix: `Extract audio from ${media.file}`
        });

        if (result.isCancelled) {
            try { await fs.unlink(tempPath); } catch { /* ignore */ }
            return {
                success: false,
                cancelled: true,
                message: 'Audio extraction cancelled by user.',
                error: 'Action cancelled by user.'
            };
        }

        if (result.success) {
            await fs.rename(tempPath, finalPath);
            logger.info(`Successfully extracted audio: ${finalPath}`);
            return {
                success: true,
                cancelled: false,
                file: finalFilename,
                saved_path: finalPath,
                message: `Audio extracted successfully! Saved as: ${finalFilename}`
            };
        } else {
            try { await fs.unlink(tempPath); } catch { /* ignore */ }
            const err = result.error || `FFmpeg exit code ${result.code}`;
            return {
                success: false,
                cancelled: false,
                message: `Failed to extract audio from ${media.file}. ${err}`,
                error: err
            };
        }
    } catch (err) {
        logger.error('Audio extraction error:', err);
        return {
            success: false,
            cancelled: false,
            message: `Error during audio extraction: ${errorMessage(err)}`,
            error: errorMessage(err)
        };
    } finally {
        taskManager.endTask(task);
    }
}

/** Download a video with subtitles and burn the subtitles into the video with ffmpeg. */
export async function downloadWithHardsub(options: HardsubOptions, onProgress: Progress = noop): Promise<ConversionResult> {
    const { url, browser, downloadFolder, subtitleLang, subtitleType, codec, subtitlePosition = 'bottom', proxy } = options;
    logger.info('Download with hardsub:', { url, subtitleLang, subtitleType, codec, subtitlePosition, downloadFolder });

    let task;
    try {
        task = taskManager.startTask('hardsub');
    } catch (err) {
        return {
            success: false,
            cancelled: false,
            message: `Error: ${errorMessage(err)}`,
            error: errorMessage(err),
            tmpFiles: []
        };
    }

    const hasSubtitles = await checkFfmpegSubtitlesSupport();
    if (!hasSubtitles) {
        taskManager.endTask(task);
        return {
            success: false,
            cancelled: false,
            message:
                'Hardsubbing requires FFmpeg with libass support (missing "subtitles" filter).\n\n👉 On macOS, please install FFmpeg with subtitles support:\n   - MacPorts: sudo port install ffmpeg\n   - Homebrew: brew install ffmpeg-full',
            error: 'FFmpeg lacks libass / subtitles filter support.',
            tmpFiles: []
        };
    }

    const cancelledResult = (): ConversionResult => ({
        success: false,
        cancelled: true,
        message: 'Hardsub cancelled by user.',
        error: 'Action cancelled by user.',
        tmpFiles: []
    });

    try {
        // Step 1: Download video with subtitle (highest quality available)
        const manifestFile = join(getScratchDirectory(), `ytdl-sub-${Date.now()}-${Math.random().toString(36).slice(2, 7)}.txt`);
        const subsFlag = subtitleType === 'manual' ? '--write-subs' : '--write-auto-subs';
        const args = [
            '--no-playlist',
            '-f', 'bestvideo+bestaudio/best',
            subsFlag, '--sub-langs', subtitleLang,
            '--convert-subs', 'vtt',
            '--write-thumbnail', '--convert-thumbnails', 'jpg',
            '--print-to-file', 'after_move:filepath', manifestFile,
            '-P', downloadFolder
        ];
        if (proxy) args.push('--proxy', proxy);
        if (browser) args.push('--cookies-from-browser', browser);
        args.push(url);

        onProgress('Downloading video and subtitles...');
        logger.info('Download command:', args);

        let capturedDownloadPath: string | null = null;
        const outputLines: string[] = [];
        const downloadCode = await new Promise<number | null>((resolve) => {
            let child;
            try {
                child = taskManager.spawnProcess(task, 'yt-dlp', args);
            } catch {
                resolve(-1);
                return;
            }

            const flushFilters = attachLineStreamFilters(child, (line) => {
                const trimmed = line.trim();
                if (isProgressLine(trimmed) || trimmed.startsWith('[download]')) {
                    onProgress(trimmed);
                } else if (trimmed) {
                    outputLines.push(trimmed);
                }
                const mergeMatch = trimmed.match(/^\[Merger\] Merging formats into ["']?(.+?)["']?$/i);
                if (mergeMatch) capturedDownloadPath = mergeMatch[1];
                const destMatch = trimmed.match(/^\[download\] Destination:\s+["']?(.+?)["']?$/i);
                if (destMatch && !capturedDownloadPath) capturedDownloadPath = destMatch[1];
            });

            child.on('close', (code) => {
                flushFilters();
                resolve(code);
            });
        });

        // Determine downloaded file path from manifest or stdout capture
        let downloadedFilePath: string | null = capturedDownloadPath;
        try {
            const manifestContent = await fs.readFile(manifestFile, 'utf8');
            const lines = manifestContent.trim().split(/[\r\n]+/);
            if (lines[0] && lines[0].trim()) {
                downloadedFilePath = lines[0].trim();
            }
        } catch { /* ignore if manifest not written */ }

        try { await fs.unlink(manifestFile); } catch { /* ignore */ }

        if (task.isCancelled) {
            return cancelledResult();
        }
        if (downloadCode !== 0) {
            const errorDetail = outputLines.join('\n') || `Download failed with code ${downloadCode}`;
            return {
                success: false,
                cancelled: false,
                message: errorDetail,
                error: errorDetail,
                tmpFiles: []
            };
        }

        // Step 2: Find downloaded files
        if (task.isCancelled) {
            return cancelledResult();
        }

        const media = await findHardsubSourceFiles(downloadFolder, subtitleLang, downloadedFilePath);
        if (!media) {
            return {
                success: false,
                cancelled: false,
                message: 'Error: Video or subtitle file not found after download.',
                error: 'Video or subtitle file not found after download.',
                tmpFiles: []
            };
        }

        const { videoPath, subtitlePath, thumbnailPath, videoName } = media;
        const codecSuffix = codec === 'hevc' ? '_HEVC' : '_H264';
        const outputPath = join(downloadFolder, `${videoName}${codecSuffix}_temp.mp4`);

        logger.info('Video file:', videoPath);
        logger.info('Subtitle file:', subtitlePath);
        logger.info('Output path:', outputPath);

        if (task.isCancelled) {
            return cancelledResult();
        }

        // Use the shorter edge so portrait and landscape footage at the same resolution share a bitrate tier.
        const probe = await probeMedia(videoPath);
        const video = probe.ok ? summarizeMediaInfo(probe.data, videoName).video : null;
        const videoHeight = video?.width && video.height ? Math.min(video.width, video.height) : video?.height ?? undefined;
        if (task.isCancelled) return cancelledResult();

        // Step 3: Run ffmpeg with hardsub
        onProgress(`Hardcoding subtitles using ${codec.toUpperCase()}...`);

        const result = await runFfmpegWithCodecFallback({
            task,
            onProgress,
            buildArgs: (audioCodec, softwareVideo) => buildFfmpegHardsubArgs({
                videoPath, outputPath, subtitlePath, thumbnailPath, codec, audioCodec, videoHeight, subtitlePosition, softwareVideo
            }),
            outputPath,
            logPrefix: 'Hardcoding',
            h264Fallback: process.platform === 'darwin' && codec !== 'hevc'
        });

        if (result.isCancelled) {
            logger.info('Hardsub was cancelled. Cleaning up temporary output only...');
            try { await fs.unlink(outputPath); } catch { /* ignore */ }
            return cancelledResult();
        }

        if (result.success) {
            const finalPath = join(downloadFolder, `${videoName}${codecSuffix}.mp4`);
            await fs.rename(outputPath, finalPath);

            logger.info(`Successfully created hardsub video: ${finalPath}`);
            const tmpFiles = [];
            if (videoPath !== finalPath) tmpFiles.push(videoPath);
            if (subtitlePath && subtitlePath !== finalPath) tmpFiles.push(subtitlePath);
            if (thumbnailPath && thumbnailPath !== finalPath) tmpFiles.push(thumbnailPath);

            return {
                success: true,
                cancelled: false,
                message: `Hardsub completed! Saved as: ${videoName}${codecSuffix}.mp4`,
                tmpFiles: offerTempFiles(tmpFiles)
            };
        } else {
            try { await fs.unlink(outputPath); } catch { /* ignore */ }
            const errorDetail = result.lastError || `FFmpeg exit code ${result.lastCode}`;
            return {
                success: false,
                cancelled: false,
                message: `Failed to create hardsub video. ${errorDetail}`,
                error: errorDetail,
                tmpFiles: []
            };
        }
    } catch (error) {
        logger.error('Hardsub error:', error);
        return {
            success: false,
            cancelled: false,
            message: `Error during hardsub: ${errorMessage(error)}`,
            error: errorMessage(error),
            tmpFiles: []
        };
    } finally {
        taskManager.endTask(task);
    }
}

/**
 * Temporary files this process has offered to delete (leftovers of a finished re-encode or hardsub).
 * Only these can be deleted through `deleteTemporaryFiles`, so a caller cannot use it to remove
 * arbitrary files.
 */
const offeredTempFiles = new Set<string>();

function offerTempFiles(paths: string[]) {
    for (const p of paths) offeredTempFiles.add(p);
    return paths;
}

/** Delete temporary files previously reported in a result's `tmpFiles`; ignores everything else. */
export async function deleteTemporaryFiles(paths: unknown) {
    if (!Array.isArray(paths)) return;
    for (const p of paths) {
        if (typeof p === 'string' && offeredTempFiles.has(p)) {
            offeredTempFiles.delete(p);
            try {
                await fs.unlink(p);
            } catch (e) {
                if (!(e instanceof Error && 'code' in e && e.code === 'ENOENT')) {
                    logger.error('Error cleaning up temp file:', p, errorMessage(e));
                }
            }
        }
    }
}
